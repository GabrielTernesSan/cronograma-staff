import type { Assunto, Pilar, TipoLeitura } from "../types";

// Cada assunto é um nó da trilha. Subtópicos, leituras e prática são marcáveis.
// Leituras: [título, fonte, url, tipo]. Só links verificados; nada de capítulo inventado.
type L = [string, string, string, TipoLeitura];
const a = (mes: number, slug: string, pilar: Pilar, titulo: string, resumo: string, subtopicos: string[], leituras: L[], pratica: string): Assunto => {
  const id = `m${String(mes).padStart(2, "0")}-${slug}`;
  return {
    id, mes, pilar, titulo, resumo,
    subtopicos: subtopicos.map((texto, i) => ({ id: `${id}-s${i + 1}`, texto })),
    leituras: leituras.map(([titulo, fonte, url, tipo], i) => ({ id: `${id}-r${i + 1}`, titulo, fonte, url, tipo })),
    pratica: { id: `${id}-p`, texto: pratica },
  };
};

